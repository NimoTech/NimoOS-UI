// Shared world-map geometry for Photos SVG maps.
// Plate carrée (equirectangular) projection.
// Land mask rasterized from Natural Earth 110m land data, 2.5° grid.
// Ported verbatim from Vue2 src/views/Photos/worldMap.js — do not change the
// four geometry constants or the mask-parsing algorithm (P6 复用同一份).

export const MAP_W = 1000
export const MAP_H = 500

export const MAP_STEP = 2.5
export const MAP_LAT_TOP = 84

export interface ProjectedPoint {
  x: number
  y: number
}

export interface WorldDot extends ProjectedPoint {
  lon: number
  lat: number
}

// Equirectangular projection: lon/lat → SVG viewBox coordinates.
export function project(lon: number, lat: number): ProjectedPoint {
  return {
    x: ((lon + 180) / 360) * MAP_W,
    y: ((90 - lat) / 180) * MAP_H,
  }
}

