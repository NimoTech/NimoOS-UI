// Pre-computed SVG dot positions for all land cells. Generated once at module load.
export const WORLD_DOTS: ReadonlyArray<WorldDot> = (() => {
  const dots: WorldDot[] = []
  for (let r = 0; r < LAND_MASK.length; r++) {
    const row = LAND_MASK[r]
    for (let c = 0; c < row.length; c++) {
      if (row[c] === '#') {
        const lon = -180 + c * MAP_STEP + MAP_STEP / 2
        const lat = MAP_LAT_TOP - r * MAP_STEP - MAP_STEP / 2
        const { x, y } = project(lon, lat)
        dots.push({ x, y, lon, lat })
      }
    }
  }
  return dots
})()
